"""Shared helpers for the reviewer analyses.

Every analysis here writes into its own folder,
`results/reviewer_outputs/<name>/`, and nowhere else:

  report.md      the numbers, under the reviewer's own wording
  summary.json   the same numbers, machine-readable
  cells.csv      one row per world (and depth, arm, ...) the summary is built from

Nothing in `results/` outside `reviewer_outputs/` is written, and no stored
record is modified.  Re-running an analysis overwrites only its own folder.

R² follows App. B.4 and `analysis/common.py`: 1 - SS(obs - pred) / SS(obs -
mean(obs)), nothing fitted.
"""

import csv
import json
import os

import _boot  # noqa: F401
import _paths  # noqa: F401
from _paths import RESULTS

import numpy as np

OUT_ROOT = os.path.join(RESULTS, "reviewer_outputs")


def out_dir(name):
    """`results/reviewer_outputs/<name>/`, created if needed."""
    d = os.path.join(OUT_ROOT, name)
    os.makedirs(d, exist_ok=True)
    return d


def r2(obs, pred):
    obs, pred = np.ravel(obs), np.ravel(pred)
    return float(1 - np.sum((obs - pred) ** 2) / np.sum((obs - obs.mean()) ** 2))


def _plain(x):
    if isinstance(x, dict):
        return {k: _plain(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_plain(v) for v in x]
    if isinstance(x, np.generic):
        return x.item()
    if isinstance(x, np.ndarray):
        return x.tolist()
    return x


def write_outputs(name, title, question, report_lines, summary, cells, source):
    """Write report.md, summary.json and cells.csv for one analysis."""
    d = out_dir(name)
    md = ["# %s" % title, "", "Reviewer comment: %s" % question, "",
          "Generated by `code/reviewer/%s.py`. Source: %s." % (name, source), ""]
    md += report_lines
    with open(os.path.join(d, "report.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")
    with open(os.path.join(d, "summary.json"), "w", encoding="utf-8") as f:
        json.dump(_plain(dict(analysis=name, question=question, source=source,
                              summary=summary)), f, indent=2)
    if cells:
        keys = list(cells[0])
        with open(os.path.join(d, "cells.csv"), "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=keys)
            w.writeheader()
            for row in cells:
                w.writerow({k: _plain(v) for k, v in row.items()})
    print("\n".join(report_lines))
    print("wrote %s" % d)
    return d
